import fs from 'node:fs/promises';
import path from 'node:path';

const root = '/workspace';
const metadataPath = path.join(root, 'metadata', 'contracts.json');
const rustOutputPath = path.join(root, 'src', 'generated_contracts.rs');
const tsOutputPath = path.join(root, 'docs-site', 'src', 'generated', 'contracts.ts');
const examplesOutputPath = path.join(root, 'docs-site', 'src', 'generated', 'examples.ts');
const quickstartExamplePath = path.join(root, 'docs', 'examples', 'quickstart-counter.tsx');
const checkMode = process.argv.includes('--check');

const metadata = JSON.parse(await fs.readFile(metadataPath, 'utf8'));
const quickstartExample = await fs.readFile(quickstartExamplePath, 'utf8');

function stableJson(value) {
  return JSON.stringify(value, null, 2);
}

function toRustArray(items) {
  return items.map((item) => `    "${item}",`).join('\n');
}

function buildRust() {
  const runtimeImports = metadata.runtimeApi.map((entry) => entry.name);
  const uiComponents = metadata.uiComponents.map((entry) => entry.name);

  return `// This file is generated by scripts/generate-contracts.mjs.\n// Do not edit manually.\n\n#[allow(dead_code)]\npub const SIGIL_VERSION: &str = "${metadata.version}";\npub const RUNTIME_IMPORTS: &[&str] = &[\n${toRustArray(runtimeImports)}\n];\npub const ALL_UI_COMPONENTS: &[&str] = &[\n${toRustArray(uiComponents)}\n];\n`;
}

function buildTs() {
  const runtimeStable = metadata.runtimeApi.filter((entry) => entry.stability === 'stable');
  const runtimeBeta = metadata.runtimeApi.filter((entry) => entry.stability === 'beta');
  const runtimeCompat = metadata.runtimeApi.filter((entry) => entry.stability === 'compat');
  const runtimeExperimental = metadata.runtimeApi.filter((entry) => entry.stability === 'experimental');

  return `// This file is generated by scripts/generate-contracts.mjs.\n// Do not edit manually.\n\nexport const SIGIL_VERSION = ${stableJson(metadata.version)};\nexport const SIGIL_RUNTIME_API = ${stableJson(metadata.runtimeApi)} as const;\nexport const SIGIL_UI_COMPONENTS = ${stableJson(metadata.uiComponents)} as const;\nexport const SIGIL_RUNTIME_IMPORTS = ${stableJson(metadata.runtimeApi.map((entry) => entry.name))} as const;\nexport const SIGIL_UI_COMPONENT_COUNT = ${metadata.uiComponents.length};\nexport const SIGIL_RUNTIME_STABLE = ${stableJson(runtimeStable)} as const;\nexport const SIGIL_RUNTIME_BETA = ${stableJson(runtimeBeta)} as const;\nexport const SIGIL_RUNTIME_COMPAT = ${stableJson(runtimeCompat)} as const;\nexport const SIGIL_RUNTIME_EXPERIMENTAL = ${stableJson(runtimeExperimental)} as const;\n`;
}

function buildExamplesTs() {
  return `// This file is generated by scripts/generate-contracts.mjs.\n// Do not edit manually.\n\nexport const QUICKSTART_COUNTER_EXAMPLE = ${stableJson(quickstartExample)};\n`;
}

async function writeOrCheck(targetPath, nextContent) {
  let currentContent = '';
  try {
    currentContent = await fs.readFile(targetPath, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  if (currentContent === nextContent) {
    return;
  }

  if (checkMode) {
    throw new Error(`Generated file is out of date: ${path.relative(root, targetPath)}`);
  }

  await fs.mkdir(path.dirname(targetPath), { recursive: true });
  await fs.writeFile(targetPath, nextContent);
}

await writeOrCheck(rustOutputPath, buildRust());
await writeOrCheck(tsOutputPath, buildTs());
await writeOrCheck(examplesOutputPath, buildExamplesTs());

if (!checkMode) {
  console.log('Generated contracts and docs metadata.');
}
